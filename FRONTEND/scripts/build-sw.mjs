/**
 * Post-build: writes out/sw.js with a precache list of every file in the static export,
 * so after one online visit the whole app (POS included) opens with no connection.
 * The cache name includes a content hash, so each deploy replaces the old cache.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const OUT = 'out';
if (!existsSync(OUT)) {
  console.error('build-sw: "out" folder not found — run next build first');
  process.exit(1);
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const hash = createHash('sha256');
const files = walk(OUT)
  .filter((f) => !f.endsWith('sw.js') && !f.endsWith('.txt') && !f.endsWith('.map'))
  .map((f) => {
    hash.update(readFileSync(f));
    let url = '/' + relative(OUT, f).split(sep).join('/');
    // Pages are served at their folder URL (trailingSlash: true)
    if (url.endsWith('/index.html')) url = url.slice(0, -'index.html'.length);
    return url;
  })
  .sort();

const version = hash.digest('hex').slice(0, 12);
const sw = `/* Generated by scripts/build-sw.mjs — do not edit. */
const CACHE = 'aivs-pos-${version}';
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // Cache one by one so a single failure does not abort the whole install.
      await Promise.all(PRECACHE.map((url) => cache.add(new Request(url, { cache: 'reload' })).catch(() => {})));
    }).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('aivs-pos-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Only the app's own files. API calls go to the network and are handled by the app's offline logic.
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    // Network first for pages (fresh deploys), fall back to the cached page, then to the POS.
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        })
        .catch(async () => {
          const cache = await caches.open(CACHE);
          const path = url.pathname.endsWith('/') ? url.pathname : url.pathname + '/';
          return (await cache.match(path)) || (await cache.match(url.pathname)) || (await cache.match('/pos/')) || Response.error();
        }),
    );
    return;
  }

  // Static assets: cache first (they are content-hashed), then network.
  event.respondWith(
    caches.match(req, { ignoreSearch: url.pathname.startsWith('/_next/static/') }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(OUT, 'sw.js'), sw);
console.log(`build-sw: precached ${files.length} files (cache ${version})`);
